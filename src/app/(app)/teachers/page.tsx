import Link from 'next/link';
import { requireSession } from '@/lib/auth';
import { query } from '@/lib/db';
import { fmtDateTime } from '@/lib/time';
import { getSettings } from '@/lib/settings';
import { ActionForm } from '@/components/ActionForm';
import { Badge, PageHead } from '@/components/ui';
import { createTeacher } from '../../actions/admin';

export const metadata = { title: 'Teachers' };

export default async function TeachersPage() {
  await requireSession(['school_admin']);
  const tz = (await getSettings()).timezone;
  const [teachers, depts] = await Promise.all([
    query<any>(`select t.id, t.teacher_no, t.first_name, t.last_name, t.phone, u.email, u.status, u.last_login_at, d.name as dept,
                  (select count(*)::int from teacher_class_subject_assignments a where a.teacher_id=t.id and a.status='active') as loads
                from teacher_profiles t join users u on u.id=t.user_id left join departments d on d.id=t.department_id order by t.last_name, t.first_name`),
    query<any>("select id,name from departments where status='active' order by name"),
  ]);
  return (
    <div className="stack">
      <PageHead title="Teachers" sub="Teacher numbers are generated by the system. A teacher sees only the classes and subjects assigned to them." />
      <details className="panel" open={!teachers.length}><summary>Add teacher and create account</summary><div>
        <ActionForm action={createTeacher} submit="Create teacher" className="form-grid">
          <div><label htmlFor="t-f">First name</label><input id="t-f" name="first" required /></div>
          <div><label htmlFor="t-l">Last name</label><input id="t-l" name="last" required /></div>
          <div><label htmlFor="t-e">Email or username</label><input id="t-e" name="email" required autoCapitalize="none" /></div>
          <div><label htmlFor="t-p">Phone</label><input id="t-p" name="phone" inputMode="tel" placeholder="0244 000 000" /></div>
          <div><label htmlFor="t-d">Department (optional)</label><select id="t-d" name="department"><option value="">None</option>{depts.map((d: any) => <option key={d.id} value={d.id}>{d.name}</option>)}</select></div>
        </ActionForm></div></details>
      <div className="card flat tablewrap"><table>
        <thead><tr><th>No.</th><th>Name</th><th>Sign-in</th><th>Department</th><th className="num">Classes and subjects</th><th>Last sign-in</th><th>Status</th><th></th></tr></thead>
        <tbody>{teachers.map((t: any) => (
          <tr key={t.id}><td>{t.teacher_no}</td><td><strong>{t.last_name}, {t.first_name}</strong></td><td className="small">{t.email}</td><td>{t.dept}</td><td className="num">{t.loads}</td>
            <td className="small">{t.last_login_at ? fmtDateTime(t.last_login_at, tz) : 'Never'}</td><td><Badge tone={t.status === 'active' ? 'ok' : ''}>{t.status}</Badge></td>
            <td><Link className="btn ghost sm" href={`/teachers/${t.id}`}>Manage</Link></td></tr>))}
          {!teachers.length && <tr><td colSpan={8} className="empty">No teachers yet. Add one above or use the Import Centre.</td></tr>}
        </tbody></table></div>
    </div>
  );
}
