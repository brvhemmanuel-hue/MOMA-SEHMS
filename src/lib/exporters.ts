const headerLines = (m: ReportMeta): [string, string][] => [
  ['School', m.school], ['Report', m.title], ['Date range', m.dateRange], ['Scope', m.scope],
  ['Filters applied', m.filtersApplied], ['Generated by', m.generatedBy], ['Generated at', m.generatedAt], ['Figures', m.basis],
];

const csvEscape = (v: unknown) => {
  const s = String(safeCell(v) ?? '');
  return /[",\n\r]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
};

export function toCsv(meta: ReportMeta, r: ReportResult): Buffer {
  const lines: string[] = [];
  for (const [k, v] of headerLines(meta)) lines.push(`${csvEscape(k)},${csvEscape(v)}`);
  if (r.note) lines.push(`Note,${csvEscape(r.note)}`);
  lines.push('');
  lines.push(r.columns.map((c) => csvEscape(c.label)).join(','));
  for (const row of r.rows) lines.push(r.columns.map((c) => csvEscape(row[c.key])).join(','));
  return Buffer.from('\ufeff' + lines.join('\r\n'), 'utf8'); // BOM so Excel reads UTF-8 correctly
}

export async function toXlsx(meta: ReportMeta, r: ReportResult): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = meta.generatedBy;
  const ws = wb.addWorksheet(meta.title.slice(0, 30).replace(/[\\/?*[\]:]/g, ' '));
  const lines = headerLines(meta);
  if (r.note) lines.push(['Note', r.note]);
  lines.forEach(([k, v], i) => {
    ws.getCell(i + 1, 1).value = k; ws.getCell(i + 1, 1).font = { bold: true };
    ws.getCell(i + 1, 2).value = String(safeCell(v));
  });
  const hr = lines.length + 2;
  r.columns.forEach((c, i) => {
    const cell = ws.getCell(hr, i + 1);
    cell.value = c.label;
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1B2F6B' } };
    cell.alignment = { wrapText: true, vertical: 'middle' };
  });
  r.rows.forEach((row, ri) => r.columns.forEach((c, ci) => {
    const v = safeCell(row[c.key]);
    ws.getCell(hr + 1 + ri, ci + 1).value = v as any;
  }));
  r.columns.forEach((c, i) => {
    const longest = Math.max(c.label.length, ...r.rows.slice(0, 200).map((x) => String(x[c.key] ?? '').length));
    ws.getColumn(i + 1).width = Math.min(Math.max(longest + 2, 12), 48);
  });
  ws.getColumn(1).width = Math.max(ws.getColumn(1).width ?? 0, 18);
  ws.views = [{ state: 'frozen', ySplit: hr }];
  return Buffer.from(await wb.xlsx.writeBuffer());
}

const latin = (s: unknown) => String(s ?? '').replace(/[^\x20-\x7E\u00A0-\u00FF]/g, '?');

function fit(font: PDFFont, text: string, size: number, width: number) {
  let t = latin(text);
  if (font.widthOfTextAtSize(t, size) <= width) return t;
  while (t.length > 1 && font.widthOfTextAtSize(t + '...', size) > width) t = t.slice(0, -1);
  return t + '...';
}

export async function toPdf(meta: ReportMeta, r: ReportResult): Promise<Buffer> {
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  let logo: any = null;
  try { logo = await pdf.embedPng(fs.readFileSync(path.join(process.cwd(), 'public', 'emblem.png'))); } catch { /* logo optional */ }
  const W = 841.89, H = 595.28, M = 36; // A4 landscape
  const navy = rgb(0.106, 0.184, 0.42), gold = rgb(0.96, 0.78, 0.1), grey = rgb(0.45, 0.45, 0.5);
  const usable = W - M * 2;
  const weight = (c: { key: string; label: string }) => Math.max(
    Math.min(Math.max(0, ...r.rows.slice(0, 300).map((x) => String(x[c.key] ?? '').length)), 34),
    ...c.label.split(' ').map((w) => w.length), 6) + 2;
  const total = r.columns.reduce((a, c) => a + weight(c), 0);
  const widths = r.columns.map((c) => (weight(c) / total) * usable);
  const SIZE = 8, ROW = 15;
  const pages: PDFPage[] = []; let page: PDFPage = pdf.addPage([W, H]); pages.push(page); let y = 0;

  const drawHead = (first: boolean) => {
    if (pages.length > 1 || y !== 0) { page = pdf.addPage([W, H]); pages.push(page); }
    y = H - M;
    if (first) {
      page.drawRectangle({ x: 0, y: H - 10, width: W, height: 10, color: navy });
      page.drawRectangle({ x: 0, y: H - 13, width: W, height: 3, color: gold });
      y -= 12;
      if (logo) page.drawImage(logo, { x: M, y: y - 46, width: 46, height: 46 });
      page.drawText(latin(meta.school), { x: M + 58, y: y - 16, size: 15, font: bold, color: navy });
      page.drawText(latin(meta.title), { x: M + 58, y: y - 34, size: 12, font: bold });
      y -= 58;
      const lines = headerLines(meta).slice(2);
      if (r.note) lines.push(['Note', r.note]);
      for (const [k, v] of lines) {
        page.drawText(latin(k + ':'), { x: M, y, size: 8, font: bold });
        page.drawText(fit(font, v, 8, usable - 90), { x: M + 86, y, size: 8, font });
        y -= 11;
      }
      y -= 6;
    } else {
      page.drawText(latin(`${meta.school} | ${meta.title}`), { x: M, y: y - 4, size: 8, font: bold, color: navy });
      y -= 20;
    }
  };

  const drawColumnHeader = () => {
    const HH = 24;
    page.drawRectangle({ x: M, y: y - HH + 4, width: usable, height: HH, color: navy });
    let x = M;
    r.columns.forEach((c, i) => {
      const words = latin(c.label).split(' '); const lines: string[] = []; let cur = '';
      for (const w of words) { const t = cur ? cur + ' ' + w : w; if (cur && bold.widthOfTextAtSize(t, SIZE) > widths[i] - 6) { lines.push(cur); cur = w; } else cur = t; }
      lines.push(cur);
      lines.slice(0, 2).forEach((ln, k) => page.drawText(fit(bold, ln, SIZE, widths[i] - 6), { x: x + 3, y: y - 7 - k * 9, size: SIZE, font: bold, color: rgb(1, 1, 1) }));
      x += widths[i];
    });
    y -= HH;
  };

  drawHead(true);

  if (r.chart && r.chart.values.length) {
    const ch = 110, cw = usable;
    page.drawText(latin(r.chart.title), { x: M, y: y - 2, size: 9, font: bold, color: navy });
    const base = y - ch - 14;
    const max = Math.max(100, ...r.chart.values);
    const n = r.chart.values.length, slot = cw / n, bw = Math.min(slot * 0.6, 36);
    page.drawLine({ start: { x: M, y: base }, end: { x: M + cw, y: base }, thickness: 0.5, color: grey });
    r.chart.values.forEach((v, i) => {
      const h = (v / max) * ch;
      page.drawRectangle({ x: M + i * slot + (slot - bw) / 2, y: base, width: bw, height: h, color: navy });
      page.drawText(`${v}%`, { x: M + i * slot + (slot - bw) / 2, y: base + h + 2, size: 6.5, font });
      if (n <= 16) page.drawText(fit(font, r.chart!.labels[i].replace('Week of ', ''), 6.5, slot - 2), { x: M + i * slot + 2, y: base - 9, size: 6.5, font, color: grey });
    });
    y = base - 24;
  }

  if (!r.columns.length) {
    page.drawText(latin(r.note || 'No data for this report.'), { x: M, y: y - 10, size: 10, font });
  } else {
    drawColumnHeader();
    if (!r.rows.length) page.drawText('No records match these filters.', { x: M + 3, y: y - 8, size: 9, font });
    r.rows.forEach((row, ri) => {
      if (y - ROW < M + 14) { drawHead(false); drawColumnHeader(); }
      if (ri % 2 === 1) page.drawRectangle({ x: M, y: y - ROW + 4, width: usable, height: ROW, color: rgb(0.95, 0.96, 0.99) });
      let x = M;
      r.columns.forEach((c, i) => {
        const text = fit(font, String(row[c.key] ?? ''), SIZE, widths[i] - 6);
        const tw = font.widthOfTextAtSize(text, SIZE);
        page.drawText(text, { x: c.num ? x + widths[i] - 3 - tw : x + 3, y: y - 7, size: SIZE, font });
        x += widths[i];
      });
      y -= ROW;
    });
  }

  pages.forEach((p, i) => {
    p.drawText(latin(`Figures: ${meta.basis}`), { x: M, y: 18, size: 6.5, font, color: grey, maxWidth: usable - 80 } as any);
    p.drawText(`Page ${i + 1} of ${pages.length}`, { x: W - M - 50, y: 18, size: 7, font, color: grey });
  });
  return Buffer.from(await pdf.save());
}

