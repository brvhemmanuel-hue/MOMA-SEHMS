/** Teachers create their own accounts and choose their classes and subjects, so they are not importable. */
export const IMPORT_ORDER: EntityKey[] = ['classes', 'subjects', 'students', 'external_admin'];

/** Optional read-only column present in files exported by the system; identifies the exact record on re-import. */
export const REFERENCE_COLUMN = 'reference';

/** Columns that must never be imported. Flagged, ignored, never stored. */
export const FORBIDDEN_COLUMN = /^(id|password|temp_password|temporary_password|teacher_id|teacher_no|teacher_number|student_id|student_id_or_index_number|student_no|student_number|index_number|class_code|subject_code)$/;

/** Header text as written in a file -> internal column name. Accepts "FIRST NAME", "First Name", "class" and so on. */
export function normaliseHeader(raw: string): string {
  const h = raw.trim().toLowerCase().replace(/[\s\-]+/g, '_');
  const alias: Record<string, string> = { class: 'class_name', classes: 'class_name', sex: 'gender', surname: 'last_name', firstname: 'first_name', lastname: 'last_name', other_name: 'other_names', year: 'academic_year' };
  return alias[h] ?? h;
}
