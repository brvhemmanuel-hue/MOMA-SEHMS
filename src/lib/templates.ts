import 'server-only';
import ExcelJS from 'exceljs';
import { ENTITIES, IMPORT_ORDER, REFERENCE_COLUMN, type EntityKey } from './import-defs';
import { query } from './db';
import { safeCell } from './validators';

const head = (ws: ExcelJS.Worksheet, headers: string[]) => {
  ws.addRow(headers);
  const r = ws.getRow(1);
  r.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  r.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1B2F6B' } };
  headers.forEach((h, i) => { ws.getColumn(i + 1).width = Math.max(h.length + 4, 18); });
  ws.views = [{ state: 'frozen', ySplit: 1 }];
};

export async function templateWorkbook(): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  const ins = wb.addWorksheet('Instructions');
  ins.getColumn(1).width = 110;
  [
    'MOMA-SEHMS import templates',
    '',
    'IDs are generated by the system. Never add teacher, student, class or subject IDs or codes, and never add passwords. Such columns are ignored.',
    'Keep every column header exactly as shown. Files with altered or missing headers are rejected.',
    'Recommended order: Academic year and terms (created in the app) > Classes > Subjects > Students > External Admin.',
    'Classes: use names like BASIC 4 A. Put Upper Primary or JHS in level_or_year. Teachers choose their level, classes and subjects themselves when they sign up.',
    'Status values: active or inactive (any capitalisation). Gender: male or female (or blank).',
    'Class names must be unique within an academic year. Subject names must be unique across the school.',
    'The External Administrator is matched on email_or_username. Classes on class_name plus academic_year. Subjects on subject_name.',
    'Referenced values (academic year, class, department) must already exist.',
    'Teachers are not imported: they create their own accounts. Temporary sign-in details for the External Administrator are shown once after import and never stored in these files.',
    'Delete the example row before uploading, or leave it out.',
  ].forEach((t, i) => { const c = ins.addRow([t]); if (i === 0) c.font = { bold: true, size: 14 }; c.alignment = { wrapText: true }; });
  for (const key of IMPORT_ORDER) {
    const d = ENTITIES[key];
    const ws = wb.addWorksheet(d.sheet);
    head(ws, d.display ?? d.headers);
    ws.addRow(d.example).font = { italic: true, color: { argb: 'FF888888' } };
  }
  return Buffer.from(await wb.xlsx.writeBuffer());
}

/** Current data in template layout plus the read-only reference column, for offline correction and re-import. */
export async function exportEntity(entity: EntityKey): Promise<Buffer> {
  const d = ENTITIES[entity];
  let rows: any[][] = [];
  if (entity === 'classes') rows = (await query<any>(`select c.name, c.level, c.programme, y.name y, c.status, c.class_code from classes c join academic_years y on y.id=c.academic_year_id order by y.start_date desc, c.name`)).map((r) => [r.name, r.level, r.programme, r.y, r.status, r.class_code]);
  if (entity === 'subjects') rows = (await query<any>(`select s.name, d.name dept, s.status, s.subject_code from subjects s left join departments d on d.id=s.department_id order by s.name`)).map((r) => [r.name, r.dept, r.status, r.subject_code]);
  if (entity === 'teachers') rows = (await query<any>(`select t.first_name, t.last_name, u.email, t.phone, d.name dept, u.status, t.teacher_no from teacher_profiles t join users u on u.id=t.user_id left join departments d on d.id=t.department_id order by t.last_name`)).map((r) => [r.first_name, r.last_name, r.email, r.phone, r.dept, r.status, r.teacher_no]);
  if (entity === 'external_admin') rows = (await query<any>(`select full_name, email, phone, status, '' as ref from users where role='external_admin' order by full_name`)).map((r) => [r.full_name, r.email, r.phone, r.status, '']);
  if (entity === 'students') rows = (await query<any>(`select s.first_name, s.last_name, s.gender, c.name cname, s.student_no from student_profiles s
      left join student_class_history h on h.student_id=s.id and h.effective_to is null left join classes c on c.id=h.class_id order by c.name, s.last_name, s.first_name`)).map((r) => [r.first_name, r.last_name, r.gender === 'male' ? 'M' : r.gender === 'female' ? 'F' : '', r.cname, r.student_no]);
  if (entity === 'teacher_assignments') rows = (await query<any>(`select u.email, c.name cname, sb.name sname, y.name y, t.name term, a.status from teacher_class_subject_assignments a
      join teacher_profiles tp on tp.id=a.teacher_id join users u on u.id=tp.user_id join classes c on c.id=a.class_id join subjects sb on sb.id=a.subject_id join terms t on t.id=a.term_id join academic_years y on y.id=a.academic_year_id order by y.name desc, u.email`)).map((r) => [r.email, r.cname, r.sname, r.y, r.term, r.status]);
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet(d.sheet);
  const hasRef = entity !== 'teacher_assignments';
  const cols = d.display ?? d.headers;
  head(ws, hasRef ? [...cols, REFERENCE_COLUMN] : cols);
  for (const r of rows) ws.addRow(r.map((v) => safeCell(v)));
  return Buffer.from(await wb.xlsx.writeBuffer());
}

/** A single-sheet template (xlsx) or CSV for one type, with the headers and one example row. */
export async function entityTemplate(entity: EntityKey, format: 'xlsx' | 'csv'): Promise<{ body: Buffer; type: string; name: string }> {
  const d = ENTITIES[entity];
  if (format === 'csv') {
    const esc = (v: string) => (/[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);
    const csv = '\ufeff' + [(d.display ?? d.headers).map(esc).join(','), d.example.map(esc).join(',')].join('\r\n') + '\r\n';
    return { body: Buffer.from(csv, 'utf8'), type: 'text/csv; charset=utf-8', name: `${entity}-template.csv` };
  }
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet(d.sheet);
  head(ws, d.display ?? d.headers);
  ws.addRow(d.example).font = { italic: true, color: { argb: 'FF888888' } };
  return { body: Buffer.from(await wb.xlsx.writeBuffer()), type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', name: `${entity}-template.xlsx` };
}
