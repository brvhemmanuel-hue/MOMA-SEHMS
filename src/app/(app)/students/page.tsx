import { requireSession } from '@/lib/auth';
import { query } from '@/lib/db';
import { ActionForm } from '@/components/ActionForm';
import { Badge, PageHead, Pager } from '@/components/ui';
import { saveStudent } from '../../actions/admin';

export const metadata = { title: 'Students' };
const PER = 40;

export default async function StudentsPage({ searchParams }: { searchParams: { q?: string; class?: string; page?: string } }) {
  await requireSession(['school_admin']);
  const q = (searchParams.q || '').trim().slice(0, 60);
  const classId = /^[0-9a-f-]{36}$/i.test(searchParams.class || '') ? searchParams.class! : '';
  const page = Math.max(1, Number(searchParams.page) || 1);
  const classes = await query<any>("select c.id, c.name, y.name as year from classes c join academic_years y on y.id=c.academic_year_id where c.status='active' order by y.start_date desc, c.name");
  const params: any[] = [];
  const w: string[] = [];
  if (q) { params.push(`%${q.toLowerCase()}%`); w.push(`(lower(s.first_name||' '||s.last_name) like $${params.length} or lower(s.student_no) like $${params.length})`); }
  if (classId) { params.push(classId); w.push(`h.class_id = $${params.length}`); }
  const where = w.length ? 'where ' + w.join(' and ') : '';
  const total = Number((await query<any>(`select count(*) n from student_profiles s left join student_class_history h on h.student_id=s.id and h.effective_to is null ${where}`, params))[0].n);
  const rows = await query<any>(
    `select s.*, c.name as class_name, c.id as class_id from student_profiles s
       left join student_class_history h on h.student_id=s.id and h.effective_to is null left join classes c on c.id=h.class_id
       ${where} order by s.last_name, s.first_name limit ${PER} offset ${(page - 1) * PER}`, params);
  const pages = Math.max(1, Math.ceil(total / PER));
  const opts = classes.map((c: any) => <option key={c.id} value={c.id}>{c.name} ({c.year})</option>);
  return (
    <div className="stack">
      <PageHead title="Students" sub="Student numbers are generated by the system. Students do not have accounts." />
      <details className="panel" open={!total && !q}><summary>Add student</summary><div>
        <ActionForm action={saveStudent} submit="Create student" className="form-grid">
          <div><label>First name</label><input name="first" required /></div><div><label>Last name</label><input name="last" required /></div>
          <div><label>Other names</label><input name="other" /></div>
          <div><label>Gender</label><select name="gender"><option value="">Not stated</option><option value="male">Male</option><option value="female">Female</option></select></div>
          <div><label>Class</label><select name="class" required><option value="">Choose class</option>{opts}</select></div>
        </ActionForm></div></details>
      <form className="row card"><div style={{ flex: '1 1 220px' }}><label htmlFor="q">Search name or number</label><input id="q" name="q" defaultValue={q} /></div>
        <div style={{ flex: '1 1 200px' }}><label htmlFor="cl">Class</label><select id="cl" name="class" defaultValue={classId}><option value="">All classes</option>{opts}</select></div>
        <button className="btn" style={{ alignSelf: 'end' }}>Filter</button></form>
      <div className="card flat"><div className="tablewrap"><table>
        <thead><tr><th>No.</th><th>Name</th><th>Gender</th><th>Class</th><th>Status</th><th></th></tr></thead>
        <tbody>{rows.map((s: any) => (
          <tr key={s.id}><td>{s.student_no}</td><td><strong>{s.last_name}, {s.first_name}</strong> {s.other_names}</td><td>{s.gender ?? ''}</td><td>{s.class_name ?? 'No class'}</td>
            <td><Badge tone={s.status === 'active' ? 'ok' : ''}>{s.status}</Badge></td>
            <td><details className="inline"><summary className="btn ghost sm">Edit</summary>
              <div className="card" style={{ position: 'absolute', right: 16, zIndex: 4, minWidth: 300, marginTop: 4 }}>
                <ActionForm action={saveStudent} submit="Save" resetOnSuccess={false} className="stack">
                  <input type="hidden" name="id" value={s.id} />
                  <div><label>First name</label><input name="first" defaultValue={s.first_name} required /></div>
                  <div><label>Last name</label><input name="last" defaultValue={s.last_name} required /></div>
                  <div><label>Other names</label><input name="other" defaultValue={s.other_names ?? ''} /></div>
                  <div><label>Gender</label><select name="gender" defaultValue={s.gender ?? ''}><option value="">Not stated</option><option value="male">Male</option><option value="female">Female</option></select></div>
                  <div><label>Class</label><select name="class" defaultValue={s.class_id ?? ''} required>{opts}</select><span className="small muted">Changing class keeps older assignments on their original register.</span></div>
                  <div><label>Status</label><select name="status" defaultValue={s.status}><option value="active">Active</option><option value="inactive">Inactive</option></select></div>
                </ActionForm></div></details></td></tr>))}
          {!rows.length && <tr><td colSpan={6} className="empty">No students match.</td></tr>}</tbody></table></div>
        <Pager base="/students" page={page} pages={pages} params={{ q, class: classId }} /></div>
    </div>
  );
}
